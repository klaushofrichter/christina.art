import fs from 'fs';
import path from 'path';

export const CONTENT_DIR = path.join(__dirname, '..', 'content');

export type ImageEntry = {
  width: number;
  height: number;
  widths: number[];
  hash: string;
  color: string;
};

export type Work = {
  slug: string;
  title: string;
  year: number;
  medium: string;
  size?: string;
  image: ImageEntry;
};

export type Exhibition = {
  title: string;
  kind: string;
  venue: string;
  city: string;
  from: string;
  to: string;
};

export type Site = {
  artist: string;
  tagline: string;
  description: string;
  email: string;
  works: Work[];
  about: string[];
  portrait: ImageEntry | null;
  exhibitions: Exhibition[];
  /** True while any of the three content files is marked as placeholder
   *  data: the page then wears the DEMO sash. */
  demo: boolean;
};

/** The compiled content the server reads: the three source files and the
 *  image manifest, checked and merged by `npm run build` (scripts/build-content.ts). */
export const COMPILED = path.join(__dirname, 'content.json');

const DATE = /^\d{4}-\d{2}-\d{2}$/;

function readJson(dir: string, name: string): Record<string, unknown> {
  const file = path.join(dir, name);
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (err) {
    throw new Error(`content/${name}: ${(err as Error).message}`);
  }
}

/** Reads the three content files plus the generated image manifest, and
 *  checks them. Throws on anything inconsistent, so bad data fails the build
 *  (and with it the deploy) rather than going live as a half-rendered page.
 *
 *    content/bio.json          artist, tagline, description, email, bio[]
 *    content/works.json        works[]: image (slug), title, year, medium, size?
 *    content/exhibitions.json  exhibitions[]: title, kind, venue, city, from, to
 *    content/images.json       generated by `npm run images`; never hand-edited
 *
 *  Each of the three may carry "placeholder": true; any one of them does, the
 *  site shows the DEMO sash. */
export function loadSite(dir: string = CONTENT_DIR): Site {
  const bio = readJson(dir, 'bio.json');
  const worksFile = readJson(dir, 'works.json');
  const exFile = readJson(dir, 'exhibitions.json');
  const images = readJson(dir, 'images.json') as {
    works?: Record<string, ImageEntry>;
    artist?: ImageEntry;
  };

  for (const key of ['artist', 'tagline', 'description', 'email']) {
    if (typeof bio[key] !== 'string' || !bio[key]) throw new Error(`content/bio.json: "${key}" is missing`);
  }
  if (!Array.isArray(bio.bio)) throw new Error('content/bio.json: "bio" must be a list of paragraphs');
  if (!Array.isArray(worksFile.works) || !worksFile.works.length) throw new Error('content/works.json: no works');
  if (!Array.isArray(exFile.exhibitions)) throw new Error('content/exhibitions.json: "exhibitions" must be a list');

  const works: Work[] = (worksFile.works as Record<string, unknown>[]).map((w, i) => {
    const slug = String(w.image ?? '');
    const image = images.works?.[slug];
    if (!image) throw new Error(`content/works.json: work ${i + 1} names image "${slug}", which images.json does not have`);
    if (!w.title) throw new Error(`content/works.json: work "${slug}" has no title`);
    return {
      slug,
      title: String(w.title),
      year: Number(w.year),
      medium: String(w.medium ?? ''),
      size: w.size ? String(w.size) : undefined,
      image,
    };
  });

  const exhibitions: Exhibition[] = (exFile.exhibitions as Record<string, unknown>[]).map((e) => {
    for (const key of ['title', 'kind', 'venue', 'city', 'from', 'to']) {
      if (!e[key]) throw new Error(`content/exhibitions.json: an exhibition has no "${key}"`);
    }
    if (!DATE.test(String(e.from)) || !DATE.test(String(e.to))) {
      throw new Error(`content/exhibitions.json: "${e.title}" dates must be YYYY-MM-DD`);
    }
    const { title, kind, venue, city, from, to } = e as Record<string, string>;
    return { title, kind, venue, city, from, to };
  });

  return {
    artist: bio.artist as string,
    tagline: bio.tagline as string,
    description: bio.description as string,
    email: bio.email as string,
    works,
    about: (bio.bio as unknown[]).map(String),
    portrait: images.artist ?? null,
    exhibitions,
    demo: [bio, worksFile, exFile].some((f) => f.placeholder === true),
  };
}

/** What the server reads at startup: the content compiled at build time.
 *  Falls back to the sources, so tests and `npm run dev` need no build. */
export function loadCompiled(file: string = COMPILED): Site {
  if (fs.existsSync(file)) return JSON.parse(fs.readFileSync(file, 'utf8')) as Site;
  return loadSite();
}

/** Upcoming (soonest first) and past (latest first), relative to `today`.
 *  An exhibition that is on now counts as upcoming: it is still worth going. */
export function splitExhibitions(list: Exhibition[], today: Date = new Date()) {
  const iso = today.toISOString().slice(0, 10);
  const upcoming = list.filter((e) => e.to >= iso).sort((a, b) => a.from.localeCompare(b.from));
  const past = list.filter((e) => e.to < iso).sort((a, b) => b.from.localeCompare(a.from));
  return { upcoming, past };
}
